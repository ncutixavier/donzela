// Writes the Firebase client configuration from environment variables.
//
// Values come from a `.env` file in the project root, or from the process
// environment (process values win). Run before building or testing:
//
//   dart run tool/generate_firebase_config.dart
//
// Writes, all gitignored:
//   lib/firebase_options.dart
//   android/app/google-services.json
//   ios/Runner/GoogleService-Info.plist
//
// When a value is missing, a placeholder is written and a warning is printed.
// The app then runs without Firebase (offline), and tests and CI still compile.
// See .env.example for the variable names.

import 'dart:convert';
import 'dart:io';

const _placeholder = 'REPLACE_ME';

/// Values that are not secret and have a sensible default.
const _defaults = {
  'FIREBASE_PROJECT_ID': 'donzela',
  'FIREBASE_ANDROID_PACKAGE': 'health.donzela.donzela',
  'FIREBASE_IOS_BUNDLE_ID': 'health.donzela.donzela',
};

const _required = [
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_ANDROID_APP_ID',
  'FIREBASE_ANDROID_API_KEY',
  'FIREBASE_ANDROID_CLIENT_ID',
  'FIREBASE_IOS_APP_ID',
  'FIREBASE_IOS_API_KEY',
  'FIREBASE_IOS_CLIENT_ID',
  'GOOGLE_WEB_CLIENT_ID',
];

void main() {
  final env = _load();
  String v(String key) {
    final value = env[key];
    if (value != null && value.isNotEmpty) return value;
    return _defaults[key] ?? _placeholder;
  }

  final missing = _required.where((k) => (env[k] ?? '').isEmpty).toList();
  if (missing.isNotEmpty) {
    stderr.writeln('Firebase config: missing ${missing.join(', ')}.');
    stderr.writeln('Writing placeholders. Firebase will not start until these are set.');
  }

  final iosClientId = v('FIREBASE_IOS_CLIENT_ID');
  final reversed = iosClientId == _placeholder
      ? _placeholder
      : 'com.googleusercontent.apps.${iosClientId.replaceAll('.apps.googleusercontent.com', '')}';

  File('lib/firebase_options.dart').writeAsStringSync(_dartOptions(v, iosClientId));
  File('android/app/google-services.json').writeAsStringSync(_googleServices(v));
  File('ios/Runner/GoogleService-Info.plist').writeAsStringSync(_plist(v, reversed));
  stdout.writeln('Firebase config written (${missing.isEmpty ? 'complete' : 'with placeholders'}).');
  if (reversed != _placeholder) {
    stdout.writeln('Info.plist URL scheme must be: $reversed');
  }
}

/// Reads `.env` first, then overlays process variables that start with FIREBASE_ or GOOGLE_.
Map<String, String> _load() {
  final out = <String, String>{};
  final file = File('.env');
  if (file.existsSync()) {
    for (final raw in file.readAsLinesSync()) {
      final line = raw.trim();
      if (line.isEmpty || line.startsWith('#')) continue;
      final eq = line.indexOf('=');
      if (eq < 0) continue;
      final key = line.substring(0, eq).trim();
      var value = line.substring(eq + 1).trim();
      if (value.length >= 2 && (value.startsWith('"') || value.startsWith("'"))) {
        value = value.substring(1, value.length - 1);
      }
      out[key] = value;
    }
  }
  for (final e in Platform.environment.entries) {
    if (e.key.startsWith('FIREBASE_') || e.key.startsWith('GOOGLE_')) {
      out[e.key] = e.value;
    }
  }
  return out;
}

String _str(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";

String _dartOptions(String Function(String) v, String iosClientId) => '''
// GENERATED by tool/generate_firebase_config.dart from environment variables.
// Do not edit or commit this file.
// ignore_for_file: type=lint

import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart'
    show TargetPlatform, defaultTargetPlatform, kIsWeb;

/// OAuth web client ID, used by Google sign-in on Android.
const googleWebClientId = ${_str(v('GOOGLE_WEB_CLIENT_ID'))};

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      throw UnsupportedError('Firebase is not configured for web.');
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      case TargetPlatform.iOS:
        return ios;
      default:
        throw UnsupportedError('Firebase is not configured for this platform.');
    }
  }

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: ${_str(v('FIREBASE_ANDROID_API_KEY'))},
    appId: ${_str(v('FIREBASE_ANDROID_APP_ID'))},
    messagingSenderId: ${_str(v('FIREBASE_MESSAGING_SENDER_ID'))},
    projectId: ${_str(v('FIREBASE_PROJECT_ID'))},
    storageBucket: ${_str(v('FIREBASE_STORAGE_BUCKET'))},
    androidClientId: ${_str(v('FIREBASE_ANDROID_CLIENT_ID'))},
  );

  static const FirebaseOptions ios = FirebaseOptions(
    apiKey: ${_str(v('FIREBASE_IOS_API_KEY'))},
    appId: ${_str(v('FIREBASE_IOS_APP_ID'))},
    messagingSenderId: ${_str(v('FIREBASE_MESSAGING_SENDER_ID'))},
    projectId: ${_str(v('FIREBASE_PROJECT_ID'))},
    storageBucket: ${_str(v('FIREBASE_STORAGE_BUCKET'))},
    iosBundleId: ${_str(v('FIREBASE_IOS_BUNDLE_ID'))},
    iosClientId: ${_str(iosClientId)},
  );
}
''';

String _googleServices(String Function(String) v) {
  final project = v('FIREBASE_PROJECT_ID');
  final pkg = v('FIREBASE_ANDROID_PACKAGE');
  final json = {
    'project_info': {
      'project_number': v('FIREBASE_MESSAGING_SENDER_ID'),
      'project_id': project,
      'storage_bucket': v('FIREBASE_STORAGE_BUCKET'),
    },
    'client': [
      {
        'client_info': {
          'mobilesdk_app_id': v('FIREBASE_ANDROID_APP_ID'),
          'android_client_info': {'package_name': pkg},
        },
        'oauth_client': [
          {
            'client_id': v('FIREBASE_ANDROID_CLIENT_ID'),
            'client_type': 1,
            'android_info': {'package_name': pkg},
          },
          {
            'client_id': v('GOOGLE_WEB_CLIENT_ID'),
            'client_type': 3,
          },
        ],
        'api_key': [
          {'current_key': v('FIREBASE_ANDROID_API_KEY')},
        ],
        'services': {
          'appinvite_service': {'other_platform_oauth_client': []},
        },
      },
    ],
    'configuration_version': '1',
  };
  return '${const JsonEncoder.withIndent('  ').convert(json)}\n';
}

String _plist(String Function(String) v, String reversed) {
  final entries = <String, String>{
    'API_KEY': v('FIREBASE_IOS_API_KEY'),
    'GCM_SENDER_ID': v('FIREBASE_MESSAGING_SENDER_ID'),
    'PLIST_VERSION': '1',
    'BUNDLE_ID': v('FIREBASE_IOS_BUNDLE_ID'),
    'PROJECT_ID': v('FIREBASE_PROJECT_ID'),
    'STORAGE_BUCKET': v('FIREBASE_STORAGE_BUCKET'),
    'IS_ADS_ENABLED': 'false',
    'IS_ANALYTICS_ENABLED': 'true',
    'IS_APPINVITE_ENABLED': 'false',
    'IS_GCM_ENABLED': 'true',
    'IS_SIGNIN_ENABLED': 'true',
    'GOOGLE_APP_ID': v('FIREBASE_IOS_APP_ID'),
    'CLIENT_ID': v('FIREBASE_IOS_CLIENT_ID'),
    'REVERSED_CLIENT_ID': reversed,
  };
  final buf = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="UTF-8"?>')
    ..writeln('<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">')
    ..writeln('<plist version="1.0">')
    ..writeln('<dict>');
  entries.forEach((key, value) {
    final isBool = value == 'true' || value == 'false';
    buf.writeln('\t<key>$key</key>');
    buf.writeln(isBool ? '\t<$value/>' : '\t<string>${_xml(value)}</string>');
  });
  buf
    ..writeln('</dict>')
    ..writeln('</plist>');
  return buf.toString();
}

String _xml(String s) =>
    s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
